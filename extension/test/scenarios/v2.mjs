// The extension UI on a fresh profile: onboarding in the full page, then the popup's screens.
export default async ({ page, shot, click, wait, id }) => {
  const home = async () => {
    const t0 = Date.now();
    await page.goto(`chrome-extension://${id}/popup.html`);
    await page.waitForSelector(".hdr, input[type=password]", { timeout: 20000 });
    console.log("popup ready in", Date.now() - t0, "ms");
    await wait(300);
  };
  await page.setViewport({ width: 900, height: 700, deviceScaleFactor: 1 });
  await page.goto(`chrome-extension://${id}/app.html`);
  await wait(4000);
  await shot("00-app-welcome");
  await click("Start");
  await click("Create a new wallet");
  await wait(800);
  await click("Tap to show the words");
  const words = await page.evaluate(() => [...document.querySelectorAll(".mono.ellipsis")].map((e) => e.textContent.trim()));
  await click("I wrote them down");
  const asked = await page.evaluate(() => [...[...document.querySelectorAll("#root > div")].pop().querySelectorAll("input")].map((i) => Number(i.placeholder.replace(/\D/g, "")) - 1));
  const inputs = await page.$$("#root > div:last-of-type input");
  for (let k = 0; k < 3; k++) await inputs[k].type(words[asked[k]]);
  await click("Continue");
  await click("Continue");
  await shot("01-password");
  const pw = await page.$$("input[type=password]");
  await pw[0].type("correct horse 42");
  await pw[1].type("correct horse 42");
  await click("Create the wallet");
  await wait(5000);
  await shot("02-app-home");

  await page.setViewport({ width: 360, height: 600, deviceScaleFactor: 2 });
  await page.goto(`chrome-extension://${id}/popup.html`);
  await wait(3000);
  await shot("10-home");
  await page.evaluate(() => document.querySelector("button[aria-label=Menu]").click());
  await wait(400);
  await shot("11-menu");
  await page.keyboard.press("Escape");
  await page.mouse.click(10, 590);
  await wait(400);
  await page.evaluate(() => document.querySelector(".wallet-pick").click());
  await wait(600);
  await shot("12-wallets");
  await page.evaluate(() => document.querySelector("button[aria-label=Cancel]").click());
  await wait(500);
  const address = await page.evaluate(() => document.querySelector(".addr-chip")?.title);
  await click("Receive");
  await wait(800);
  await shot("13-receive");
  await page.evaluate(() => document.querySelector("button[aria-label=Back]")?.click());
  await wait(500);
  // Zero balance: Send is off; force it to look at the screens.
  await page.evaluate(() => [...document.querySelectorAll("button.action")][1].removeAttribute("disabled"));
  await click("Send");
  await wait(600);
  await shot("14-send-to");
  await page.focus("#root > div:last-of-type input");
  await page.keyboard.type(address);
  await wait(800);
  await shot("15-send-typed");
  await page.keyboard.press("Enter");
  await wait(600);
  await shot("16-amount");
  await page.focus("input[inputmode=decimal]");
  await page.keyboard.type("0.01");
  await click("Continue");
  await wait(1500);
  await shot("16b-review");
  await home();
  await page.evaluate(() => document.querySelector("button[aria-label=Menu]").click());
  await wait(300);
  await click("Settings");
  await wait(700);
  await shot("17-settings");
  await page.evaluate(() => [...document.querySelectorAll(".scroll")].pop().scrollTo(0, 600));
  await wait(300);
  await shot("18-settings-mid");
  await page.evaluate(() => [...document.querySelectorAll(".scroll")].pop().scrollTo(0, 3000));
  await wait(300);
  await shot("19-settings-end");
  await home();
  await page.evaluate(() => document.querySelector("button[aria-label=Menu]").click());
  await wait(300);
  await click("Address book");
  await wait(600);
  await shot("20-contacts");
  await home();
  await page.evaluate(() => document.querySelector("button[aria-label=Menu]").click());
  await wait(300);
  await click("Lock ZApp");
  await wait(1200);
  await shot("21-locked");
  await page.type("input[type=password]", "correct horse 42");
  await page.keyboard.press("Enter");
  await wait(2500);
  await shot("22-unlocked");
  await page.emulateMediaFeatures([{ name: "prefers-color-scheme", value: "dark" }]);
  await wait(500);
  await shot("23-dark");
  await page.goto(`chrome-extension://${id}/sidepanel.html`);
  await wait(3000);
  await shot("24-sidepanel");
};
